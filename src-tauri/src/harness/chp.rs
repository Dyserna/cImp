/// The CHP event a live push route carries, or `None` for a route that carries
/// none (the hello, a reserved route, a route that is not CHP at all).
///
/// Derived from [`EVENTS`] for the same reason [`is_push_route`] is: the quiet
/// detector below joins on event ids, and a second hand-kept route table is how
/// a new event ends up observed for staleness but invisible to arbitration.
pub fn event_for_route(route: &str) -> Option<&'static str> {
    EVENTS
        .iter()
        .find(|e| e.live && e.route != HELLO_ROUTE && e.route == route)
        .map(|e| e.id)
}

/// Whether `route` carries a CHP message that can be *attributed* — i.e. a
/// live, non-hello route whose body cImp defines end to end.
///
/// Derived from [`EVENTS`] rather than restated, so a new event is observed for
/// staleness by being added to the vocabulary and not by remembering a second
/// list. `/session/hello` is excluded because its own handler records a richer
/// fact than an observation.
pub fn is_push_route(route: &str) -> bool {
    EVENTS
        .iter()
        .any(|e| e.live && e.route != HELLO_ROUTE && e.route == route)
}

// ── who is expected to speak CHP ────────────────────────────────────────────

/// Whether cImp *generates a CHP-speaking artifact* for this harness — and so
/// whether an absent or old `chp` from it means **stale**.
///
/// `opencode` yes: `tabs::config::opencode_plugin_source` bakes [`CHP_VERSION`]
/// into every plugin it writes, so a POST carrying less than that came from a
/// file an older build wrote.
///
/// `claude` **yes, since V35 Phase J**. Its L1 used to be five stateless shim
/// binaries with nowhere to put a version, which is why Phase I answered `false`
/// here (locked decision 5, recorded rather than assumed). Phase J replaced them
/// with `type: "http"` hooks whose emitted entries carry `X-CIMP-Chp` —
/// substituted from [`CHP_VERSION`] at overlay generation, exactly as the
/// generated OpenCode plugin substitutes it — so a Claude tab is now a
/// spawn-baked artifact that states its version, and the same three staleness
/// arms apply to it.
///
/// **The day that flipped, every Claude tab open across the upgrade started
/// reporting `old_plugin`.** That is the intended reading, not a false positive:
/// such a tab really is running an overlay full of `cimp --context-hook` command
/// hooks that this build no longer generates, and *restart the tab* really is
/// the fix. It is the V32 "needs a FRESH TAB" trap being named at exactly the
/// moment it applies.
pub fn expects_chp(agent: &str) -> bool {
    // V40 Phase A: the registry answers it. It was a hard-coded disjunction, so
    // stale-artifact detection was silently OFF for any harness not named in it
    // — a new harness would have shipped with the mechanism disabled and no
    // diff saying so.
    crate::harness::HarnessId::from_id(agent)
        .and_then(|h| h.descriptor())
        .is_some_and(|d| d.expects_chp)
}

// ── the per-tab peer registry ───────────────────────────────────────────────

/// One `cannot` entry from a hello: a capability this harness will **not**
/// serve, and why (design D3). Recorded and displayed in Phase I; nothing gates
/// on it until Phase L.
#[derive(Debug, Clone, Default, PartialEq, Eq, serde::Serialize)]
pub struct Unable {
    pub id: String,
    pub why: String,
}

/// What cImp knows about one tab's harness-side artifact.
///
/// In-memory and non-durable for the same reason the latch registry is: it
/// describes a *live* plugin in a *live* tab, and an app restart ends every one
/// of them. **Bounded** the same way too — the only writer validates the tab id
/// against the user's configured AI tabs before it inserts, so the key space is
/// `configured AI tabs × 2 agents`, not "whatever a request body said".
#[derive(Debug, Clone, Default, PartialEq, Eq, serde::Serialize)]
pub struct Peer {
    /// `claude` / `opencode`, already normalized through `source_for_consumer`.
    pub agent: String,
    pub tab: String,
    /// The highest-authority `chp` seen from this tab: a hello's if one has
    /// arrived, otherwise the last routed POST's. [`PRE_CHP`] when the artifact
    /// predates Phase I.
    pub chp: u32,
    /// The harness version the hello declared. **Empty is the normal case in
    /// Phase I** — OpenCode exposes no version to a plugin at module scope, so
    /// its hello omits the field; Claude sends no hello at all yet. The
    /// comparison [`stale_for`] makes with it is implemented and tested, and its
    /// producer arrives with Phase J.
    pub harness_version: String,
    /// What this artifact says it will do (design D3). Recorded, displayed,
    /// **not gated on** in Phase I.
    pub serves: Vec<String>,
    pub cannot: Vec<Unable>,
    /// When the last hello landed. `0` = none has.
    pub hello_at_ms: u64,
    /// When anything was last heard from this tab.
    pub seen_at_ms: u64,
    /// V35 Phase L — the quiet detector's counters: for each served capability
    /// that has a [`witness_of`] entry, how many WITNESS pushes have arrived
    /// since that capability last pushed (or since the hello).
    ///
    /// Reset wholesale by a hello, which is right: a hello is a fresh
    /// declaration from a (re)loaded artifact, so counting against the previous
    /// one would report the old artifact's silence as the new one's.
    #[serde(skip)]
    pub quiet_counters: BTreeMap<String, u32>,
    /// Capabilities already reported quiet for this artifact — the once-per-
    /// (tab, capability) latch, so a permanently dead hook costs one report and
    /// not one per turn. `Doubling` is the loopback's ledger for repeats; this
    /// is the cheaper "say it once" the ledger sits behind.
    #[serde(skip)]
    pub quiet_reported: BTreeSet<String>,
}

impl Peer {
    /// Whether a hello has ever arrived from this tab.
    pub fn greeted(&self) -> bool {
        self.hello_at_ms > 0
    }
}

/// The process-wide peer registry. See [`Peer`] for the bound.
fn peers() -> &'static Mutex<HashMap<(String, String), Peer>> {
    static PEERS: OnceLock<Mutex<HashMap<(String, String), Peer>>> = OnceLock::new();
    PEERS.get_or_init(Default::default)
}

fn lock() -> std::sync::MutexGuard<'static, HashMap<(String, String), Peer>> {
    peers().lock().unwrap_or_else(PoisonError::into_inner)
}

/// Whether this exact `(agent, tab, chp)` has already been recorded.
///
/// The cheap pre-check on the hot path: every prompt, every tool call and every
/// gate query carries a `chp`, and the *second* one from a tab says nothing new.
/// Its caller uses this to decide whether the observation is worth a settings
/// read (which is what validates the tab id), so the steady state costs one map
/// lookup per POST rather than one `Settings` clone per POST.
pub fn already_seen(agent: &str, tab: &str, chp: u32) -> bool {
    lock()
        .get(&(agent.to_string(), tab.to_string()))
        .is_some_and(|p| p.chp == chp)
}

/// Record a `chp` observed on a routed POST from a **validated** tab.
///
/// A hello outranks a routed POST for the same tab: the hello is the artifact's
/// own declaration and carries the version and the capability lists, so a bare
/// observation never overwrites it downwards — but a *changed* value does, since
/// that is the tab having been relaunched with a different artifact.
pub fn note_push(agent: &str, tab: &str, chp: u32, at_ms: u64) {
    let mut peers = lock();
    let e = peers
        .entry((agent.to_string(), tab.to_string()))
        .or_default();
    if e.agent.is_empty() {
        e.agent = agent.to_string();
        e.tab = tab.to_string();
    }
    if e.chp != chp {
        // The artifact changed under us — drop the hello's claims rather than
        // keep attributing them to a file that no longer says them.
        if e.greeted() {
            e.hello_at_ms = 0;
            e.serves.clear();
            e.cannot.clear();
            e.harness_version.clear();
        }
        // V35 Phase L: the quiet counters belong to the declaration they were
        // opened against. A different artifact makes them meaningless, and
        // keeping them would report the previous plugin's silence as this one's.
        e.quiet_counters.clear();
        e.quiet_reported.clear();
        e.chp = chp;
    }
    e.seen_at_ms = at_ms;
}

/// Record a `/session/hello` from a **validated** tab. Returns `true` when this
/// changed what cImp knows — which is what the handler keys its Activity row on,
/// so a re-hello identical to the stored one writes nothing.
#[allow(clippy::too_many_arguments)]
pub fn note_hello(
    agent: &str,
    tab: &str,
    chp: u32,
    harness_version: &str,
    serves: Vec<String>,
    cannot: Vec<Unable>,
    at_ms: u64,
) -> bool {
    let next = Peer {
        agent: agent.to_string(),
        tab: tab.to_string(),
        chp,
        harness_version: harness_version.to_string(),
        serves,
        cannot,
        hello_at_ms: at_ms,
        seen_at_ms: at_ms,
        ..Default::default()
    };
    let mut peers = lock();
    let key = (agent.to_string(), tab.to_string());
    let changed = match peers.get(&key) {
        // Timestamps are not part of the comparison: a plugin that re-hellos
        // unchanged must not be able to write a row per hello.
        Some(prev) => {
            prev.chp != next.chp
                || prev.harness_version != next.harness_version
                || prev.serves != next.serves
                || prev.cannot != next.cannot
                || !prev.greeted()
        }
        None => true,
    };
    peers.insert(key, next);
    changed
}

// ── V35 Phase L: arbitration — push wins WHEN SERVED ────────────────────────

/// **The arbitration rule, spelled once**: is `event` being pushed for this
/// exact `(agent, tab)`?
///
/// `true` ⇒ the fallback reader's output for THAT capability on THAT tab is
/// suppressed. `false` ⇒ the reader serves it, exactly as it did before Phase L.
/// Three properties, and each one closes a specific way this could go wrong:
///
/// * **Per capability.** A tab that pushes assistant text still has its
///   transcript tailed for usage and identity, which no hook payload carries
///   (see [`EVENTS`]). Suppressing a whole reader because one of its five taps
///   migrated is how a migration loses data.
/// * **Per tab.** Two Claude tabs can be running two different spawn-baked
///   overlays; one may push and the other (launched before the upgrade) may
///   not. A process-wide switch would mute the older tab entirely.
/// * **Only when the tab has actually spoken.** `greeted()` is required, not
///   just a non-empty `serves`: the declaration arrives *over the push path*,
///   so a hello is itself the proof that the path works. A pre-upgrade tab
///   sends none, gets `false` here, and behaves exactly as it did on `develop`
///   — which is what makes the migration safe to ship with old tabs open.
///
/// It is deliberately NOT "the capability is wired in settings": settings say
/// what cImp *asked* for; the hello says what the artifact on disk actually
/// does, and those two differ for precisely as long as a stale tab stays open
/// (§ 6.1).
pub fn served(agent: &str, tab: &str, event: &str) -> bool {
    lock()
        .get(&(agent.to_string(), tab.to_string()))
        .is_some_and(|p| p.greeted() && p.serves.iter().any(|s| s == event))
}

/// How many WITNESS pushes may arrive with a served capability silent before
/// that silence is reported as drift.
///
/// Three, not one: a single turn can legitimately end without the witnessed
/// event (an interrupted turn, a `/clear`), and reporting on the first one
/// would train the reader to ignore the notice — the exact failure V16's
/// tripwire had and this milestone exists to avoid.
pub const QUIET_WITNESS_PUSHES: u32 = 3;

/// The event whose arrival PROVES a served capability should also have pushed
/// — the "demonstrably active" half of locked decision 7.
///
/// A witness is only sound when the implication is exact, so the list is short
/// and every entry states the implication:
///
/// * `assistant_text` ← `prompt`: every prompt a harness accepts ends in a
///   final assistant message, so a `UserPromptSubmit` with no `Stop` behind it
///   is the `Stop` hook having stopped firing.
/// * `session.tool_result` ← `context.post_edit`: the post-edit hook fires on
///   `Edit|Write|MultiEdit`, and the tool-result hook fires on the SAME event
///   with an all-tools matcher, so an edit that produced one and not the other
///   is the wider entry having gone.
///
/// `session.subagent` deliberately has **none**: a session may legitimately
/// launch no sub-agents, forever, so there is no arrival that proves one should
/// have been reported. Inventing a threshold there would manufacture false
/// reports, which is worse than the gap — the gap is at least declared here.
pub fn witness_of(event: &str) -> Option<&'static str> {
    match event {
        EV_ASSISTANT_TEXT => Some(EV_PROMPT),
        EV_SESSION_TOOL_RESULT => Some(EV_CONTEXT_POST_EDIT),
        _ => None,
    }
}

/// Record one push of `event` from `(agent, tab)` and return the served
/// capabilities that have just gone QUIET.
///
/// **Locked decision 7: a served capability going silent must NOT quietly fall
/// back to the reader.** Falling back would restore the data and hide the
/// breakage — which is the silent-drift class this whole milestone exists to
/// delete. So the reader stays suppressed while the hello's claim stands, and
/// the silence is *reported* instead: each returned id gets a
/// `drift.payload.v1` row, which the Advisor already consolidates per
/// capability.
///
/// **Never inserts.** A peer this process has not validated (§ the handler's
/// `is_configured_tab` check) has no entry, so an unknown tab cannot grow the
/// map here — the counters ride an entry the validated path created.
pub fn note_event(agent: &str, tab: &str, event: &str) -> Vec<String> {
    let mut peers = lock();
    let Some(peer) = peers.get_mut(&(agent.to_string(), tab.to_string())) else {
        return Vec::new();
    };
    if !peer.greeted() {
        return Vec::new();
    }
    // This capability just pushed: it is demonstrably alive, so its counter
    // goes back to zero — including after a report, so a hook that recovers
    // stops being counted against its own past silence.
    if peer.serves.iter().any(|s| s == event) {
        peer.quiet_counters.insert(event.to_string(), 0);
    }
    // …and every served capability WITNESSED by this event moves one step
    // closer to being reported.
    let mut quiet: Vec<String> = Vec::new();
    let watched: Vec<String> = peer
        .serves
        .iter()
        .filter(|s| witness_of(s) == Some(event) && s.as_str() != event)
        .cloned()
        .collect();
    for id in watched {
        let n = peer.quiet_counters.entry(id.clone()).or_insert(0);
        *n = n.saturating_add(1);
        if *n >= QUIET_WITNESS_PUSHES && peer.quiet_reported.insert(id.clone()) {
            quiet.push(id);
        }
    }
    quiet
}

/// Every peer cImp currently knows about, in a stable order.
pub fn snapshot() -> Vec<Peer> {
    let mut rows: Vec<Peer> = lock().values().cloned().collect();
    rows.sort_by(|a, b| (&a.agent, &a.tab).cmp(&(&b.agent, &b.tab)));
    rows
}

// ── the consumer: stale-artifact detection ──────────────────────────────────

/// Why an artifact is being reported as out of step. Machine tokens, because
/// the three cases want three different sentences and the panel must not
/// re-derive which is which from the numbers.
pub const STALE_OLD_PLUGIN: &str = "old_plugin";
pub const STALE_NEW_PLUGIN: &str = "new_plugin";
pub const STALE_VERSION: &str = "harness_version";

/// One tab whose harness-side artifact is out of step with this binary.
///
/// The V32 deploy trap, made legible: the four "needs a FRESH TAB" incidents
/// were all this, and all of them were diagnosed by a human eventually
/// remembering that plugins are spawn-baked.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
pub struct StalePlugin {
    pub tab: String,
    pub agent: String,
    /// The `chp` this tab's artifact actually sends. [`PRE_CHP`] = it sends none.
    pub seen_chp: u32,
    /// [`CHP_VERSION`] — what this binary writes into a freshly generated
    /// artifact.
    pub expected: u32,
    /// [`STALE_OLD_PLUGIN`] / [`STALE_NEW_PLUGIN`] / [`STALE_VERSION`].
    pub kind: &'static str,
    /// The sentence, written here rather than four times in a Svelte `{#if}`
    /// chain — the same rule `health::DegradationView::label` follows.
    pub note: String,
}

/// Classify one peer against this binary. `None` = in step.
///
/// Pure, so all three arms are assertable without touching the process-global
/// registry (the suite runs cases concurrently in one process).
fn classify(peer: &Peer, known_version: &str) -> Option<StalePlugin> {
    let row = |kind: &'static str, note: String| StalePlugin {
        tab: peer.tab.clone(),
        agent: peer.agent.clone(),
        seen_chp: peer.chp,
        expected: CHP_VERSION,
        kind,
        note,
    };
    // A HIGHER version than this binary knows is staleness too — the other way
    // round. An old binary is running beside a plugin a newer build wrote, which
    // is the same deploy trap seen from the downgrade side, and reading it as
    // "fine, it is at least current" would hide exactly that.
    if peer.chp > CHP_VERSION {
        return Some(row(
            STALE_NEW_PLUGIN,
            format!(
                "This tab's harness plugin speaks CHP {} — NEWER than this cImp build understands \
                 (CHP {CHP_VERSION}). The plugin was written by a newer build; this one is the \
                 stale side. Nothing is refused, but a capability the newer plugin assumes may \
                 not exist here.",
                peer.chp
            ),
        ));
    }
    if peer.chp < CHP_VERSION && expects_chp(&peer.agent) {
        let what = if peer.chp == PRE_CHP {
            "sends no `chp` field at all, so it predates CHP".to_string()
        } else {
            format!("speaks CHP {}", peer.chp)
        };
        return Some(row(
            STALE_OLD_PLUGIN,
            format!(
                "This tab's harness plugin {what} — this build writes CHP {CHP_VERSION}. The \
                 plugin file is baked at tab launch, so a tab started before the upgrade keeps \
                 the old one: RESTART THE TAB. Until then its behavior is the old build's, which \
                 is what has previously read as a mysterious failure rather than as a version \
                 mismatch."
            ),
        ));
    }
    if !peer.harness_version.is_empty()
        && !known_version.is_empty()
        && peer.harness_version != known_version
    {
        return Some(row(
            STALE_VERSION,
            format!(
                "This tab's plugin declared harness version {:?}, but the installed CLI is now \
                 {known_version:?}. The tab is running against a build cImp has not verified its \
                 contracts on — restart it, or re-run the checks.",
                peer.harness_version
            ),
        ));
    }
    None
}

/// Every out-of-step artifact for one harness, in a stable order.
///
/// `known_version` is that harness's currently-observed CLI version
/// (`harness_versions.<harness>_last_seen`); empty disables the version arm
/// rather than reporting every tab as mismatched against nothing.
pub fn stale_for(agent: &str, known_version: &str) -> Vec<StalePlugin> {
    let mut out: Vec<StalePlugin> = snapshot()
        .iter()
        .filter(|p| p.agent == agent)
        .filter_map(|p| classify(p, known_version))
        .collect();
    out.sort_by(|a, b| a.tab.cmp(&b.tab));
    out
}

// ── reading `chp` off a routed POST ─────────────────────────────────────────

/// The three fields any CHP message carries, read leniently off a body cImp
/// otherwise leaves to its route's own type.
///
/// Deliberately a *second*, tiny deserialization rather than a `chp` field added
/// to nine body structs: the routes' own types stay byte-identical (zero
/// behavior change is the phase's exit criterion), and the identity fields are
/// read here exactly as each route reads them — some spell the discriminator
/// `agent` and some `consumer`, which is a real fact about the wire and is
/// documented as such in `docs/CHP.md` rather than papered over.
#[derive(Debug, Clone, PartialEq, Eq, Default, serde::Deserialize)]
pub struct Envelope {
    /// Absent ⇒ [`PRE_CHP`]. **Never an error** — see [`PRE_CHP`].
    #[serde(default)]
    pub chp: Option<u32>,
    #[serde(default)]
    pub agent: Option<String>,
    #[serde(default)]
    pub consumer: Option<String>,
    #[serde(default)]
    pub tab: Option<String>,
}

impl Envelope {
    /// The discriminator this body carries, whichever of the two names it used.
    pub fn agent_token(&self) -> &str {
        self.agent
            .as_deref()
            .or(self.consumer.as_deref())
            .unwrap_or("")
    }
}

/// The CHP envelope of a routed POST, or `None` when there is nothing to
/// observe: a route that carries no CHP message, a body that is not JSON, or a
/// body with no tab identity to attribute the observation to.
///
/// A body that fails to parse is silently ignored, which is right for a *side*
/// observation — the route's own handler owns the 400, and an observation that
/// could reject a request would be a behavior change.
pub fn envelope(route: &str, body: &[u8]) -> Option<(Envelope, String)> {
    if !is_push_route(route) {
        return None;
    }
    let env: Envelope = serde_json::from_slice(body).ok()?;
    let tab = env.tab.as_deref().map(str::trim).filter(|t| !t.is_empty())?;
    let tab = tab.to_string();
    Some((env, tab))
}

