//! V35 Phase I — **CHP, the cImp Harness Protocol**: the name, the version and
//! the capability handshake for the wire both harnesses have already been
//! speaking for a year.
//!
//! # What was already there
//!
//! The Claude hook shims and `tabs/config.rs::opencode_plugin_source` POST the
//! same harness-neutral body to the same loopback routes, discriminated by
//! `agent`. That is a protocol; nobody had named, versioned or written it down.
//! Phase I does exactly those three things and **changes no behavior**: `chp` is
//! additive and tolerated-absent, `/session/hello` is new and nothing gates on
//! what it says (locked decision 5 — negotiation becomes load-bearing in
//! Phase L). (Phase J then deleted those shims: Claude's half of the wire is now
//! `type: "http"` hooks posting Claude's own payloads to `/claude/hook/*`, with
//! the envelope in headers — see [`crate::harness::claude::hook`].)
//!
//! The written contract is [`docs/CHP.md`](../../../../docs/CHP.md). It and
//! [`CHP_VERSION`] are kept in step by [`tests::the_doc_states_this_version`],
//! the same `include_str!` two-sources-of-truth idiom the rest of the crate
//! uses.
//!
//! # Why a version on the wire (design D5)
//!
//! The generated plugin and the `--settings` overlay are **spawn-baked**: an
//! upgraded binary with an old tab still running has an *old plugin on disk*
//! talking to *new loopback code*. V32 recorded that as a deploy trap four
//! separate times (F-13, M-16, F-23, F-32's child half), each with the same
//! mitigation — "needs a FRESH TAB or it reads as a failure". With `chp` on the
//! wire the mismatch is **detected and reported** instead of surfacing as a
//! mysterious functional failure during a live-verify. That detection is this
//! module's second half ([`stale_for`]), and the *Harness health* panel is its
//! consumer.
//!
//! # One file, on purpose
//!
//! The plugin-architecture design lays out `harness/chp/{mod,events,routes}.rs`.
//! That split belongs to **Phase K**, which moves `oob/*` and the five shims
//! into `harness/<id>/` and is the point at which a directory earns its
//! subdivision. Splitting three near-empty modules out now would be structure
//! without content — and the handlers stay in `offload/loopback.rs` regardless
//! (design § 4: *"route table; handlers stay in offload/loopback.rs"*).

use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::sync::{Mutex, OnceLock, PoisonError};

// ── the version ─────────────────────────────────────────────────────────────

/// **The** CHP version, spelled once.
///
/// Substituted into the generated OpenCode plugin at generation time
/// (`tabs::config::opencode_plugin_source`) rather than typed there as a
/// literal, echoed by `/session/hello`'s ack, and asserted equal to the version
/// in `docs/CHP.md`'s header. Bumping it is therefore a three-line change in one
/// commit, and forgetting the doc fails the build.
///
/// **Compatibility is permanent, not versioned-away.** A plugin file written at
/// tab launch outlives the binary that wrote it, so every `chp` value that has
/// ever shipped must keep being *understood* — the point of the field is to make
/// the mismatch legible, never to refuse an old artifact (design § 8).
pub const CHP_VERSION: u32 = 2;

/// What an absent `chp` field means: a **pre-CHP** artifact — a plugin or shim
/// generated by a build from before Phase I.
///
/// Absent is never an error. Global principle 5 in the other direction: this is
/// the one case where "missing" has a real, specific meaning rather than being a
/// blank that should be rejected, and the meaning is *old*, not *broken*.
pub const PRE_CHP: u32 = 0;

// ── the route surface ───────────────────────────────────────────────────────

/// The capability-negotiation route (design D3). New in Phase I.
pub const HELLO_ROUTE: &str = "/session/hello";

/// One CHP event: the name L3 will gate against (design D4) and the loopback
/// route that carries it today.
///
/// `core` is D4's small set every harness must serve to be usable at all;
/// everything else is optional and a capability declares its dependency on it.
/// `live` says whether cImp serves the route **today** — a `false` row is
/// reserved for Phase L (push the read path), and is in this table so the
/// vocabulary is one list rather than a live half plus a design doc.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Event {
    pub id: &'static str,
    pub core: bool,
    pub route: &'static str,
    pub live: bool,
}

const fn ev(id: &'static str, core: bool, route: &'static str, live: bool) -> Event {
    Event {
        id,
        core,
        route,
        live,
    }
}

